"""All pure Prepare epilogues and the remaining passage hard-block epilogue."""
from pathlib import Path
import json, re
R = Path(__file__).resolve().parent
S = R / 'evidence/movement-state-v28'
path = R / 'ra2/src/recomp/gen_game/recomp_0010.c'
data = path.read_bytes()
assert b'\r\n' not in data
text = data.decode('utf-8')
begin = text.index('void sub_004A2670')
end = text.index('\nvoid ', begin + 10)
primary = text[begin:end]
pattern = re.compile(r'    edi = POP32_VAL\(esp\); /\* 0x([0-9A-F]+): pop edi \*/(?:(?!\nL_|\n    RECOMP_CALL|\n    MEM|\n    ecx =|\n    eax =)[\s\S])*?RECOMP_REGS_OUT\(\); return; \} /\* 0x([0-9A-F]+): ret 0xc \*/')
entries = []
for match in pattern.finditer(primary):
    mode = 1 if 'SET_LO8(eax, 0)' in match[0] else 2 if 'SET_LO8(eax, 1)' in match[0] else 0
    address = match[1]
    marker = f'    edi = POP32_VAL(esp); /* 0x{address}: pop edi */'
    count = text.count(marker)
    assert count > 0
    result = 'g_eax' if not mode else '(g_eax & UINT32_C(0xFFFFFF00))' + (' | 1u' if mode == 2 else '')
    code = f'''    /* 可读 C：Prepare 共享出口，保留 EAX 高位及原栈布局。 */
    RECOMP_FLAGS_OUT(); RECOMP_REGS_OUT();
    ra2_ground_return_frame(g_esp, RA2_FRAME_PREPARE, {result});
    RECOMP_REGS_IN(); RECOMP_FLAGS_IN(); return;
'''
    text = text.replace(marker, code + marker)
    entries.append(dict(address=address, kind='RA2_FRAME_PREPARE', mode=mode, copies=count))
assert len(entries) == 26
path.write_bytes(text.encode('utf-8'))
path = R / 'ra2/src/recomp/gen_game/recomp_0046.c'
data = path.read_bytes()
assert data.count(b'\n') == data.count(b'\r\n')
text = data.decode('utf-8').replace('\r\n', '\n')
marker = 'L_00703940:\n'
count = text.count(marker)
assert count > 0
text = text.replace(marker, marker + '''    RECOMP_FLAGS_OUT(); RECOMP_REGS_OUT();
    ra2_ground_passage_return_bridge(1);
    RECOMP_REGS_IN(); RECOMP_FLAGS_IN(); return;
''')
path.write_bytes(text.replace('\n', '\r\n').encode('utf-8'))
entries.append(dict(address='00703940', kind='RA2_FRAME_PASSAGE', mode=3, copies=count))
(S/'remaining_return_cases.h').write_text('/* Generated by integrate_returns_v28.py; original native epilogue entries. */\n'
    + 'static const struct ReturnCase { uint32_t address; Ra2GroundFrameKind kind; unsigned mode; } return_cases[] = {\n'
    + ''.join(f"    {{0x{e['address']}u, {e['kind']}, {e['mode']}}},\n" for e in entries) + '};\n', encoding='utf-8', newline='\n')
(S/'pending/shared-exit-integration.json').write_text(json.dumps(dict(passed=True, entries=entries,
    unique_entries=len(entries), overlapping_copies=sum(e['copies'] for e in entries), original_labels_retained=True), indent=2)+'\n', encoding='utf-8')
print('Integrated', len(entries), 'native epilogues in', sum(e['copies'] for e in entries), 'copies')
